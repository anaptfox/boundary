/**
 * Deterministic WIT world projection from a Program.
 *
 * The emitted world is a spelling of contracts the Program already owns. It
 * carries no authority: an import listed here is a name the host *may* map to
 * a function, never a grant. Binding checks that a component's actual imports
 * are a subset of the host's map; this file only decides what the guest is
 * allowed to ask for.
 *
 * Every interaction becomes one exported function taking canonical JSON and
 * returning `result<string, string>`. The ok payload is the interaction
 * output; the err payload is a declared interaction error. Anything else is a
 * trap, and a trap is an infrastructure fault with unknown certainty, never a
 * domain error. The JSON-string profile is deliberate: JSON Schema has no
 * total mapping onto WIT records and variants, so lowering waits for an
 * explicit opt-in profile.
 *
 * This is a from-scratch TypeScript port of
 * `crates/boundary-plugin/src/wit.rs`. It must emit byte-identical WIT text
 * for the same Program and options; the shared conformance vector is the
 * check, not this comment.
 */
import { BoundaryErrorBase, type InteractionDescriptor, type Program, type Sha256Digest } from "@foxworth/boundary/program";
import { compareUtf8 } from "#program/internal";
import { NameError, witIdentifier } from "./name";

/** Generated-file banner. Present so a reader never edits the projection. */
const BANNER = "// Generated by Boundary. Do not edit.";

/** Options controlling the emitted package and world names. */
export type WitProjectionOptions = {
  /** WIT package name, such as `boundary:guest`. */
  readonly package: string;
  /** Package version, such as `1.0.0`. */
  readonly version: string;
  /** World name, such as `guest`. */
  readonly world: string;
  /** Interface name holding the host functions a guest may import. */
  readonly importsInterface: string;
};

/** Default options: `boundary:guest@1.0.0`, world `guest`, interface `footprints`. */
export const DEFAULT_WIT_PROJECTION_OPTIONS: WitProjectionOptions =
  Object.freeze({
    package: "boundary:guest",
    version: "1.0.0",
    world: "guest",
    importsInterface: "footprints",
  });

/** Why a Program has no valid WIT world. */
export type WitProjectionDiagnosticCode =
  | "NAMES_UNSPELLABLE"
  | "NAME_COLLISION"
  | "FOOTPRINT_UNSPELLABLE"
  | "FOOTPRINT_COLLISION";

/**
 * A Program that has no valid WIT world. Exactly one of `errors`,
 * (`witName`, `interactionIds`), or (`footprint`, `cause`) is populated,
 * selected by `code`.
 */
export class WitProjectionError extends BoundaryErrorBase {
  declare readonly code: WitProjectionDiagnosticCode;
  /** Every interaction id that cannot be spelled in WIT, sorted. `NAMES_UNSPELLABLE` only. */
  readonly errors?: readonly NameError[];
  /** The colliding WIT identifier. `NAME_COLLISION` only. */
  readonly witName?: string;
  /** Every interaction id that derives `witName`, sorted. `NAME_COLLISION` only. */
  readonly interactionIds?: readonly string[];
  /** The offending footprint. `FOOTPRINT_UNSPELLABLE` only. */
  readonly footprint?: string;
  /** Every footprint that derives `witName`, sorted. `FOOTPRINT_COLLISION` only. */
  readonly footprints?: readonly string[];

  private constructor(
    code: WitProjectionDiagnosticCode,
    path: string,
    message: string,
    options: Readonly<{
      cause?: unknown;
      errors?: readonly NameError[];
      witName?: string;
      interactionIds?: readonly string[];
      footprint?: string;
      footprints?: readonly string[];
    }> = {},
  ) {
    super(code, path, message, { cause: options.cause });
    this.name = "WitProjectionError";
    if (options.errors !== undefined) this.errors = options.errors;
    if (options.witName !== undefined) this.witName = options.witName;
    if (options.interactionIds !== undefined) {
      this.interactionIds = options.interactionIds;
    }
    if (options.footprint !== undefined) this.footprint = options.footprint;
    if (options.footprints !== undefined) this.footprints = options.footprints;
  }

  /** One or more interaction ids have no valid WIT spelling. Never just the first. */
  static names(errors: readonly NameError[]): WitProjectionError {
    return new WitProjectionError(
      "NAMES_UNSPELLABLE",
      "program.interactions",
      `${errors.length} interaction id(s) cannot be spelled in WIT: ${errors
        .map((error) => error.message)
        .join("; ")}`,
      { errors },
    );
  }

  /** Two distinct interaction ids derive the same WIT identifier. */
  static collision(
    witName: string,
    interactionIds: readonly string[],
  ): WitProjectionError {
    return new WitProjectionError(
      "NAME_COLLISION",
      "program.interactions",
      `WIT identifier ${JSON.stringify(witName)} is derived by more than one interaction: ${interactionIds.join(", ")}`,
      { witName, interactionIds },
    );
  }

  /** A footprint has no valid WIT spelling. */
  static footprint(footprint: string, cause: NameError): WitProjectionError {
    return new WitProjectionError(
      "FOOTPRINT_UNSPELLABLE",
      `program.footprints.${footprint}`,
      `footprint ${JSON.stringify(footprint)} cannot be spelled in WIT: ${cause.message}`,
      { cause, footprint },
    );
  }

  /**
   * Two distinct footprints derive the same WIT identifier.
   *
   * The interaction-name collision has a footprint twin, because the same
   * derivation collapses distinct sources the same way. Rendering both would
   * emit two functions with one name in a single interface: invalid WIT, and
   * a WIT digest computed over text no toolchain would accept.
   */
  static footprintCollision(
    witName: string,
    footprints: readonly string[],
  ): WitProjectionError {
    return new WitProjectionError(
      "FOOTPRINT_COLLISION",
      "program.footprints",
      `WIT identifier ${JSON.stringify(witName)} is derived by more than one footprint: ${footprints.join(", ")}`,
      { witName, footprints },
    );
  }
}

/** One projected interaction, pinning the WIT spelling to a contract identity. */
export type ProjectedInteraction = {
  /** The WIT function name. */
  readonly witName: string;
  /** The interaction id, which remains the contract identity. */
  readonly interactionId: string;
  /** The v1 contract digest. */
  readonly contractDigest: Sha256Digest;
};

/** A deterministic WIT world plus the mapping back to interaction identities. */
export type WitProjection = {
  /** The WIT source text. */
  readonly wit: string;
  /** Projected interactions, sorted by WIT name. */
  readonly interactions: readonly ProjectedInteraction[];
  /** Footprint names a guest may import, sorted. */
  readonly footprints: readonly string[];
  /** The Program digest this projection was derived from. */
  readonly programDigest: Sha256Digest;
};

function footprintList(values: readonly string[]): string {
  return values.length === 0 ? "(none)" : values.join(", ");
}

type RenderInteraction = {
  readonly witName: string;
  readonly descriptor: InteractionDescriptor;
};

/** Renders the WIT text. Every loop here walks an already-sorted collection. */
function render(
  options: WitProjectionOptions,
  programDigest: string,
  interactions: readonly RenderInteraction[],
  footprintEntries: readonly (readonly [string, string])[],
): string {
  let out = BANNER;
  out += "\n//\n";
  out += `// program: ${programDigest}\n`;
  out += `// interactions: ${interactions.length}\n`;
  out += "//\n";
  out +=
    "// Each export takes canonical JSON input and returns canonical JSON output.\n";
  out +=
    "// An `err` payload is a declared interaction error. A trap is an infrastructure\n";
  out += "// fault with unknown certainty, never a domain error.\n\n";

  out += `package ${options.package.trim()}@${options.version.trim()};\n\n`;

  out +=
    "/// Host functions a guest may import. Listing a footprint here is not a\n";
  out +=
    "/// grant: the host maps footprints to implementations at bind time, and a\n";
  out += "/// guest importing anything outside that map cannot be bound.\n";
  out += `interface ${options.importsInterface} {\n`;
  if (footprintEntries.length === 0) {
    out += "  // This program declares no reads or changes.\n";
  }
  for (const [footprint, name] of footprintEntries) {
    out += `  /// footprint: ${footprint}\n`;
    out += `  ${name}: func(request: string) -> result<string, string>;\n`;
  }
  out += "}\n\n";

  out += `world ${options.world} {\n`;
  out += `  import ${options.importsInterface};\n`;
  for (const { witName, descriptor } of interactions) {
    out += "\n";
    out += `  /// interaction: ${descriptor.contract.id}\n`;
    out += `  /// contract: ${descriptor.contractDigest}\n`;
    out += `  /// reads: ${footprintList(descriptor.contract.reads)}\n`;
    out += `  /// changes: ${footprintList(descriptor.contract.changes)}\n`;
    out += `  export ${witName}: func(input: string) -> result<string, string>;\n`;
  }
  out += "}\n";
  return out;
}

/**
 * Projects a Program into a WIT world.
 *
 * The output is a pure function of the Program and the options: the same
 * inputs always produce byte-identical text, which is what lets the Rust and
 * TypeScript projectors be checked against one shared conformance vector.
 *
 * Throws {@link WitProjectionError} when an interaction id or footprint has no
 * valid WIT spelling, or when two ids collide. The projector never resolves a
 * collision by renaming; the host must supply an explicit alias.
 */
export function projectWit(
  program: Program,
  options: Readonly<Partial<WitProjectionOptions>> = {},
): WitProjection {
  const resolved: WitProjectionOptions = {
    ...DEFAULT_WIT_PROJECTION_OPTIONS,
    ...options,
  };

  const nameErrors: NameError[] = [];
  // Keyed by WIT name, so every downstream iteration is ordered by WIT name
  // rather than by Program order.
  const byWitName = new Map<string, InteractionDescriptor[]>();
  // Keyed by the original footprint name, matching the Rust reference.
  const footprints = new Map<string, string>();
  // The reverse: WIT name back to every footprint deriving it, so a collision
  // is caught rather than rendered.
  const footprintNames = new Map<string, string[]>();

  for (const descriptor of program.interactions) {
    const id = descriptor.contract.id;
    const result = witIdentifier(id);
    if (result.ok) {
      const existing = byWitName.get(result.value);
      if (existing) existing.push(descriptor);
      else byWitName.set(result.value, [descriptor]);
    } else {
      nameErrors.push(result.error);
    }

    for (const footprint of [
      ...descriptor.contract.reads,
      ...descriptor.contract.changes,
    ]) {
      if (footprints.has(footprint)) continue;
      const footprintResult = witIdentifier(footprint);
      if (!footprintResult.ok) {
        throw WitProjectionError.footprint(footprint, footprintResult.error);
      }
      const claimed = footprintNames.get(footprintResult.value);
      if (claimed) claimed.push(footprint);
      else footprintNames.set(footprintResult.value, [footprint]);
      footprints.set(footprint, footprintResult.value);
    }
  }

  if (nameErrors.length > 0) {
    nameErrors.sort((left, right) =>
      compareUtf8(left.interactionId, right.interactionId),
    );
    throw WitProjectionError.names(nameErrors);
  }

  for (const witName of [...footprintNames.keys()].sort(compareUtf8)) {
    const sources = footprintNames.get(witName) as string[];
    if (sources.length > 1) {
      throw WitProjectionError.footprintCollision(
        witName,
        [...sources].sort(compareUtf8),
      );
    }
  }

  const witNames = [...byWitName.keys()].sort(compareUtf8);
  const renderInteractions: RenderInteraction[] = [];
  for (const witName of witNames) {
    const descriptors = byWitName.get(witName)!;
    if (descriptors.length > 1) {
      const interactionIds = descriptors
        .map((descriptor) => descriptor.contract.id)
        .sort(compareUtf8);
      throw WitProjectionError.collision(witName, interactionIds);
    }
    renderInteractions.push({ witName, descriptor: descriptors[0]! });
  }

  const footprintEntries: readonly (readonly [string, string])[] = [
    ...footprints.keys(),
  ]
    .sort(compareUtf8)
    .map((original) => [original, footprints.get(original)!] as const);

  const wit = render(
    resolved,
    program.programDigest,
    renderInteractions,
    footprintEntries,
  );

  const interactions: ProjectedInteraction[] = renderInteractions.map(
    ({ witName, descriptor }) => ({
      witName,
      interactionId: descriptor.contract.id,
      contractDigest: descriptor.contractDigest,
    }),
  );

  return Object.freeze({
    wit,
    interactions: Object.freeze(interactions),
    footprints: Object.freeze(footprintEntries.map(([, derived]) => derived)),
    programDigest: program.programDigest,
  });
}
