//! Deterministic WIT world projection from a Program.
//!
//! The emitted world is a spelling of contracts the Program already owns. It
//! carries no authority: an import listed here is a name the host *may* map to
//! a function, never a grant. Binding checks that a component's actual imports
//! are a subset of the host's map; this file only decides what the guest is
//! allowed to ask for.
//!
//! Every interaction becomes one exported function taking canonical JSON and
//! returning `result<string, string>`. The ok payload is the interaction output;
//! the err payload is a declared interaction error. Anything else is a trap, and
//! a trap is an infrastructure fault with unknown certainty, never a domain
//! error. The JSON-string profile is deliberate: JSON Schema has no total
//! mapping onto WIT records and variants, so lowering waits for an explicit
//! opt-in profile.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use boundary_core::Program;

use crate::name::{NameError, wit_identifier};

/// Generated-file banner. Present so a reader never edits the projection.
const BANNER: &str = "// Generated by Boundary. Do not edit.";

/// Options controlling the emitted package and world names.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct WitProjectionOptions {
    /// WIT package name, such as `boundary:guest`.
    pub package: String,
    /// Package version, such as `1.0.0`.
    pub version: String,
    /// World name, such as `guest`.
    pub world: String,
    /// Interface name holding the host functions a guest may import.
    pub imports_interface: String,
}

impl Default for WitProjectionOptions {
    fn default() -> Self {
        Self {
            package: "boundary:guest".to_owned(),
            version: "1.0.0".to_owned(),
            world: "guest".to_owned(),
            imports_interface: "footprints".to_owned(),
        }
    }
}

/// Why a Program has no valid WIT world.
#[derive(Clone, Debug, Eq, PartialEq, thiserror::Error)]
pub enum WitProjectionError {
    /// One or more interaction ids have no valid WIT spelling.
    #[error("{} interaction id(s) cannot be spelled in WIT: {}", .0.len(), format_names(.0))]
    Names(Vec<NameError>),
    /// Two distinct interaction ids derive the same WIT identifier.
    #[error("WIT identifier {name:?} is derived by more than one interaction: {}", interactions.join(", "))]
    Collision {
        /// The colliding WIT identifier.
        name: String,
        /// Every interaction id that derives it, sorted.
        interactions: Vec<String>,
    },
    /// A footprint has no valid WIT spelling.
    #[error("footprint {footprint:?} cannot be spelled in WIT: {source}")]
    Footprint {
        /// The offending footprint.
        footprint: String,
        /// The derivation failure.
        source: NameError,
    },
    /// Two distinct footprints derive the same WIT identifier.
    ///
    /// Without this, `render` would emit two functions with one name in a
    /// single interface — invalid WIT, and a WIT digest computed over text
    /// that no toolchain would accept.
    #[error("WIT identifier {name:?} is derived by more than one footprint: {}", footprints.join(", "))]
    FootprintCollision {
        /// The colliding WIT identifier.
        name: String,
        /// Every footprint that derives it, sorted.
        footprints: Vec<String>,
    },
}

fn format_names(errors: &[NameError]) -> String {
    errors
        .iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join("; ")
}

/// One projected interaction, pinning the WIT spelling to a contract identity.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ProjectedInteraction {
    /// The WIT function name.
    pub wit_name: String,
    /// The interaction id, which remains the contract identity.
    pub interaction_id: String,
    /// The v1 contract digest.
    pub contract_digest: String,
}

/// A deterministic WIT world plus the mapping back to interaction identities.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct WitProjection {
    /// The WIT source text.
    pub wit: String,
    /// Projected interactions, sorted by WIT name.
    pub interactions: Vec<ProjectedInteraction>,
    /// Footprint names a guest may import, sorted.
    pub footprints: Vec<String>,
    /// The Program digest this projection was derived from.
    pub program_digest: String,
}

/// Projects a Program into a WIT world.
///
/// The output is a pure function of the Program and the options: the same
/// inputs always produce byte-identical text, which is what lets the Rust and
/// TypeScript projectors be checked against one shared vector.
///
/// # Errors
///
/// Returns [`WitProjectionError`] when an interaction id or footprint has no
/// valid WIT spelling, or when two ids collide. The projector never resolves a
/// collision by renaming; the host must supply an explicit alias.
pub fn project_wit(
    program: &Program,
    options: &WitProjectionOptions,
) -> Result<WitProjection, WitProjectionError> {
    let mut name_errors = Vec::new();
    // BTreeMap keeps every downstream iteration sorted, so the emitted text is
    // ordered by WIT name rather than by Program order.
    let mut by_name: BTreeMap<String, Vec<&boundary_core::InteractionDescriptor>> = BTreeMap::new();
    let mut footprints: BTreeMap<String, String> = BTreeMap::new();
    let mut footprint_names: BTreeMap<String, Vec<String>> = BTreeMap::new();

    for descriptor in program.interactions() {
        let contract = descriptor.contract();
        let id = contract.id().as_str();
        match wit_identifier(id) {
            Ok(name) => by_name.entry(name).or_default().push(descriptor),
            Err(error) => name_errors.push(error),
        }

        for footprint in contract.reads().iter().chain(contract.changes()) {
            if footprints.contains_key(footprint) {
                continue;
            }
            match wit_identifier(footprint) {
                Ok(name) => {
                    // The interaction-name check below has a footprint twin,
                    // because the same derivation collapses distinct sources
                    // the same way. `footprints` is keyed by footprint, so
                    // two that derive one name would both survive and render
                    // as two same-named functions in one interface.
                    footprint_names
                        .entry(name.clone())
                        .or_default()
                        .push(footprint.clone());
                    footprints.insert(footprint.clone(), name);
                }
                Err(source) => {
                    return Err(WitProjectionError::Footprint {
                        footprint: footprint.clone(),
                        source,
                    });
                }
            }
        }
    }

    if !name_errors.is_empty() {
        name_errors.sort_by(|left, right| left.interaction_id.cmp(&right.interaction_id));
        return Err(WitProjectionError::Names(name_errors));
    }

    for (name, sources) in &footprint_names {
        if sources.len() > 1 {
            let mut footprints = sources.clone();
            footprints.sort();
            return Err(WitProjectionError::FootprintCollision {
                name: name.clone(),
                footprints,
            });
        }
    }

    for (name, descriptors) in &by_name {
        if descriptors.len() > 1 {
            let mut interactions: Vec<String> = descriptors
                .iter()
                .map(|descriptor| descriptor.contract().id().as_str().to_owned())
                .collect();
            interactions.sort();
            return Err(WitProjectionError::Collision {
                name: name.clone(),
                interactions,
            });
        }
    }

    let program_digest = program.digest().to_string();
    let interactions: Vec<ProjectedInteraction> = by_name
        .iter()
        .filter_map(|(name, descriptors)| {
            descriptors.first().map(|descriptor| ProjectedInteraction {
                wit_name: name.clone(),
                interaction_id: descriptor.contract().id().as_str().to_owned(),
                contract_digest: descriptor.contract_digest().to_string(),
            })
        })
        .collect();

    let wit = render(
        options,
        &program_digest,
        &interactions,
        &footprints,
        program,
    );
    Ok(WitProjection {
        wit,
        interactions,
        footprints: footprints.into_values().collect(),
        program_digest,
    })
}

/// Renders the WIT text. Every loop here iterates a sorted collection.
fn render(
    options: &WitProjectionOptions,
    program_digest: &str,
    interactions: &[ProjectedInteraction],
    footprints: &BTreeMap<String, String>,
    program: &Program,
) -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("\n//\n");
    let _ = writeln!(out, "// program: {program_digest}");
    let _ = writeln!(out, "// interactions: {}", interactions.len());
    out.push_str("//\n");
    out.push_str("// Each export takes canonical JSON input and returns canonical JSON output.\n");
    out.push_str(
        "// An `err` payload is a declared interaction error. A trap is an infrastructure\n",
    );
    out.push_str("// fault with unknown certainty, never a domain error.\n\n");

    let _ = writeln!(
        out,
        "package {}@{};\n",
        options.package.trim(),
        options.version.trim()
    );

    out.push_str("/// Host functions a guest may import. Listing a footprint here is not a\n");
    out.push_str("/// grant: the host maps footprints to implementations at bind time, and a\n");
    out.push_str("/// guest importing anything outside that map cannot be bound.\n");
    let _ = writeln!(out, "interface {} {{", options.imports_interface);
    if footprints.is_empty() {
        out.push_str("  // This program declares no reads or changes.\n");
    }
    for (footprint, name) in footprints {
        let _ = writeln!(out, "  /// footprint: {footprint}");
        let _ = writeln!(
            out,
            "  {name}: func(request: string) -> result<string, string>;"
        );
    }
    out.push_str("}\n\n");

    let _ = writeln!(out, "world {} {{", options.world);
    let _ = writeln!(out, "  import {};", options.imports_interface);
    for interaction in interactions {
        out.push('\n');
        let _ = writeln!(out, "  /// interaction: {}", interaction.interaction_id);
        let _ = writeln!(out, "  /// contract: {}", interaction.contract_digest);
        if let Some(descriptor) = program.interaction_named(&interaction.interaction_id) {
            let contract = descriptor.contract();
            let _ = writeln!(out, "  /// reads: {}", footprint_list(contract.reads()));
            let _ = writeln!(out, "  /// changes: {}", footprint_list(contract.changes()));
        }
        let _ = writeln!(
            out,
            "  export {}: func(input: string) -> result<string, string>;",
            interaction.wit_name
        );
    }
    out.push_str("}\n");
    out
}

fn footprint_list(values: &[String]) -> String {
    if values.is_empty() {
        "(none)".to_owned()
    } else {
        values.join(", ")
    }
}
