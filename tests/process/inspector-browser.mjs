// Independent packed consumer proof. Run with an already-installed archive:
// node tests/process/inspector-browser.mjs <consumer-root> <playwright-module>
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { copyFile, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'vite';

const [consumerArg, playwrightArg] = process.argv.slice(2);
if (!consumerArg || !playwrightArg) throw new Error('expected installed consumer root and Playwright module path');
const consumer = await realpath(consumerArg);
const installed = await realpath(path.join(consumer, 'node_modules/@foxworth/boundary'));
const workspace = await realpath(process.cwd());
if (installed.startsWith(`${workspace}${path.sep}`)) throw new Error('consumer resolves to workspace source');
const temp = await mkdtemp(path.join(consumer, 'inspector-proof-'));
let child, browser;
try {
  const browserEntry = path.join(temp, 'browser.mjs');
  const hostEntry = path.join(temp, 'host.mjs');
  await copyFile(new URL('../fixtures/runtimes/inspector-browser.mjs', import.meta.url), browserEntry);
  await copyFile(new URL('../fixtures/runtimes/inspector-host.mjs', import.meta.url), hostEntry);
  const output = await build({ root: consumer, configFile: false, logLevel: 'error', build: { write: false, minify: false, target: 'es2022', lib: { entry: browserEntry, formats: ['es'] } } });
  const chunks = (Array.isArray(output) ? output : [output]).flatMap(result => result.output ?? []).filter(item => item.type === 'chunk');
  assert.equal(chunks.length, 1, 'proof requires a single browser bundle');
  for (const id of Object.keys(chunks[0].modules)) assert.doesNotMatch(id, /__vite-browser-external|node:/);
  const bundle = path.join(temp, 'bundle.js');
  await writeFile(bundle, chunks[0].code);
  child = spawn(process.execPath, [hostEntry, bundle], { cwd: consumer, stdio: ['ignore', 'pipe', 'inherit'] });
  const url = await new Promise((resolve, reject) => {
    let buffer = '';
    const timer = setTimeout(() => reject(new Error('fixture server did not start')), 15000);
    child.once('error', reject);
    child.once('exit', code => reject(new Error(`fixture server exited (${code})`)));
    child.stdout.on('data', chunk => { buffer += chunk; const match = buffer.match(/INSPECTOR_URL=(http:\/\/[^\s]+)/); if (match) { clearTimeout(timer); resolve(match[1]); } });
  });
  const { chromium } = await import(pathToFileURL(await realpath(playwrightArg)).href);
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  await page.goto(url);
  const interaction = page.getByTestId('inspector-interaction');
  await interaction.first().waitFor();
  assert.equal(await interaction.count(), 3);
  assert.equal(await page.locator('[data-interaction-id="fixture.hidden"]').count(), 0);
  const change = page.locator('[data-interaction-id="fixture.change"]');
  const inspect = page.locator('[data-interaction-id="fixture.inspect"]');
  const nested = page.locator('[data-interaction-id="fixture.nested"]');
  await change.click();
  await page.getByText('Contract and identity').click();
  assert.match(await page.getByTestId('inspector-contract').innerText(), /fixture\.change/);
  assert.match(await page.getByTestId('inspector-contract').innerText(), /inspector:fixture:change/);
  const input = page.getByTestId('inspector-input');
  const invoke = page.getByTestId('inspector-invoke');
  const counts = async () => (await (await fetch(`${url}/effects`, { headers: { authorization: 'inspector-fixture-private-credential' } })).json());
  const effects = async () => (await counts()).effects;
  await input.fill('"x"');
  await invoke.click();
  await page.waitForTimeout(150);
  assert.equal(await effects(), 0, 'invalid schema input reached dispatch');
  await input.fill('"unknown"');
  await invoke.click();
  await page.getByTestId('inspector-outcome').getByText(/unknown/i).waitFor();
  const unknownSummary = page.locator('summary').filter({ hasText: /fixture\.change.*direct.*unknown/i });
  await unknownSummary.waitFor();
  await unknownSummary.focus();
  await page.keyboard.press('Enter');
  assert.match(await unknownSummary.locator('..').getByTestId('inspector-attempt').innerText(), /unknown/i);
  assert.equal(await effects(), 1);
  await page.waitForTimeout(300);
  assert.equal(await effects(), 1, 'unknown was retried');
  await input.fill('"success"');
  await invoke.click();
  await page.getByTestId('inspector-outcome').getByText(/completed/i).waitFor();
  assert.deepEqual(await counts(), { effects: 2, proposals: 0 });
  await input.fill('"slow-disconnect"');
  await invoke.click();
  const attempts = page.getByTestId('inspector-attempt');
  const disconnectedAttempt = attempts.filter({ hasText: 'slow-disconnect' });
  await disconnectedAttempt.waitFor({ state: 'attached' });
  assert.match(await disconnectedAttempt.locator('..').locator('summary').innerText(), /fixture\.change.*direct.*pending/i);
  await page.evaluate(() => window.inspectorFixture.disconnect());
  assert.match(await disconnectedAttempt.locator('..').locator('summary').innerText(), /fixture\.change.*pending/i);
  await page.waitForFunction(() => [...document.querySelector('[data-boundary-inspector]').shadowRoot.querySelectorAll('[data-testid="inspector-attempt"]')].some(el => el.textContent.includes('slow-disconnect') && el.textContent.includes('completed')));
  assert.equal(await effects(), 3);
  assert.match(await disconnectedAttempt.textContent(), /completed/i);
  await page.evaluate(() => window.inspectorFixture.reconnect());
  await change.waitFor();
  await change.click();
  await input.fill('"slow-switch"');
  await invoke.click();
  const switchedAttempt = attempts.filter({ hasText: 'slow-switch' });
  await switchedAttempt.waitFor({ state: 'attached' });
  assert.match(await switchedAttempt.locator('..').locator('summary').innerText(), /fixture\.change.*pending/i);
  await inspect.click();
  assert.match(await switchedAttempt.locator('..').locator('summary').innerText(), /fixture\.change.*pending/i);
  await page.waitForFunction(() => [...document.querySelector('[data-boundary-inspector]').shadowRoot.querySelectorAll('[data-testid="inspector-attempt"]')].some(el => el.textContent.includes('slow-switch') && el.textContent.includes('completed')));
  assert.match(await switchedAttempt.textContent(), /completed/i);
  assert.ok(!(await page.getByTestId('inspector-outcome').innerText()).includes('slow-switch'), 'old result overwrote the selected interaction');
  assert.equal(await effects(), 4, 'switch or disconnect retried an attempt');
  await nested.click();
  await invoke.click();
  await page.getByTestId('inspector-outcome').getByText(/completed/i).waitFor();
  const nestedSummary = page.locator('summary').filter({ hasText: /fixture\.nested.*direct.*settled/i });
  await nestedSummary.waitFor();
  await nestedSummary.click();
  const nestedEvidence = await nestedSummary.locator('..').getByTestId('inspector-attempt').innerText();
  assert.match(nestedEvidence, /unknown/);
  assert.match(nestedEvidence, /completed/);
  await change.click();
  await fetch(`${url}/revoke`, { headers: { authorization: 'inspector-fixture-private-credential' } });
  await input.fill('"valid"');
  await invoke.click();
  await page.getByTestId('inspector-outcome').getByText(/revoked|not.started/i).waitFor();
  assert.equal(await effects(), 4, 'revoked binding dispatched');
  const leaks = await page.evaluate(() => [document.documentElement.outerHTML, document.querySelector('[data-boundary-inspector]')?.shadowRoot?.innerHTML ?? '', JSON.stringify(localStorage), JSON.stringify(sessionStorage)].join('\n'));
  assert.ok(!leaks.includes('inspector-fixture-private-credential'), 'credential leaked to DOM or storage');
  await page.evaluate(() => window.inspectorFixture.dispose());
  assert.equal(await page.locator('[data-boundary-inspector]').count(), 0);
  assert.deepEqual(failures, []);
  console.log(`packed inspector browser and localhost proof passed; installed=${installed}; effects=4; proposals=0`);
} finally {
  await browser?.close();
  if (child && child.exitCode === null) { child.kill('SIGTERM'); await new Promise(resolve => child.once('exit', resolve)); }
  await rm(temp, { recursive: true, force: true });
}
